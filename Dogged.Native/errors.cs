    /// <summary>
    ///  Structure to store extra details of the last error that
    ///  occurred.
    ///
    ///  <para>
    ///   This is kept on a per-thread basis if GIT_THREADS was
    ///   defined when the library was build, otherwise one is kept
    ///   globally for the library
    ///  </para>
    /// </summary>
    [StructLayout(LayoutKind.Sequential)]
    public unsafe struct git_error
    {
        /// <summary>
        ///  The error message for the last error.
        /// </summary>
        public byte* message;

        /// <summary>
        ///  The category of the last error.
        /// </summary>
        public git_error_t klass;
    }

    public static partial class libgit2
    {
        /// <summary>
        ///  Return the last `git_error` object that was generated for
        ///  the current thread.
        ///
        ///  <para>
        ///   This function will never return NULL.
        ///  </para>
        ///
        ///  <para>
        ///   Callers should not rely on this to determine whether an
        ///   error has occurred. For error checking, callers should
        ///   examine the return codes of libgit2 functions.
        ///  </para>
        ///
        ///  <para>
        ///   This call can only reliably report error messages when
        ///   an error has occurred. (It may contain stale information
        ///   if it is called after a different function that
        ///   succeeds.)
        ///  </para>
        ///
        ///  <para>
        ///   The memory for this object is managed by libgit2. It
        ///   should not be freed.
        ///  </para>
        /// </summary>
        /// <returns>
        ///  A pointer to a `git_error` object that describes the error.
        /// </returns>
        [DllImport(libgit2_dll, CallingConvention = CallingConvention.Cdecl)]
        public static extern unsafe git_error* git_error_last();
    }
}
